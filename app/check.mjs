import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

const root = resolve(process.argv[2]);
const require = createRequire(resolve(process.argv[3], 'package.json'));
const {JSDOM} = require('jsdom');
const data = JSON.parse(await readFile(root + '/cohorts.json', 'utf8'));
const {window} = new JSDOM(await readFile(root + '/index.html', 'utf8'), {url: 'https://example.test/'});
globalThis.document = window.document;
globalThis.window = window;
globalThis.localStorage = window.localStorage;
globalThis.fetch = async () => ({ok: true, json: async () => data});
let downloaded;
globalThis.URL.createObjectURL = (blob) => { downloaded = blob; return 'blob:test'; };
globalThis.URL.revokeObjectURL = () => {};
window.HTMLAnchorElement.prototype.click = function () {
  assert.equal(this.download, 'stratiq-sec-2022.json');
};
await import(pathToFileURL(root + '/main.mjs'));
await new Promise(setImmediate);
const query = (selector) => document.querySelector(selector);
assert.match(query('#cohort-summary').textContent, /29 of 40/);
assert.match(query('#correlations').textContent, /\+0\.203/);
assert.equal(document.querySelectorAll('#issuer-rows tr').length, 40);
const fire = (node, event, value) => {
  node.value = value;
  node.dispatchEvent(new window.Event(event));
};
fire(query('#year'), 'change', '2022');
assert.match(query('#cohort-summary').textContent, /27 of 40/);
fire(query('#search'), 'input', 'alphabet');
assert.match(query('#issuer-rows').textContent, /GOOGL/);
assert.equal(document.querySelectorAll('#issuer-rows tr').length, 1);
assert.equal(query('#issuer-rows a').href, 'https://www.sec.gov/edgar/browse/?CIK=1652044');
fire(query('#search'), 'input', '<script>');
assert.match(query('#issuer-rows').textContent, /No issuers/);
assert.equal(query('#issuer-rows script'), null);
fire(query('#search'), 'input', '');
fire(query('#coverage'), 'change', 'excluded');
assert.equal(document.querySelectorAll('#issuer-rows tr').length, 13);
query('#export').click();
assert.equal(JSON.parse(await downloaded.text()).feature_year, 2022);
fire(query('#coverage'), 'change', 'all');
const savedButton = () => query('button[data-cik="1652044"]');
savedButton().click();
assert.equal(savedButton().getAttribute('aria-pressed'), 'true');
assert.equal(document.activeElement, savedButton());
assert.deepEqual(JSON.parse(localStorage.getItem('stratiq.watchlist.v1')), ['1652044']);
query('#saved-only').click();
assert.equal(document.querySelectorAll('#issuer-rows tr').length, 1);
fire(query('#year'), 'change', '2023');
assert.equal(savedButton().getAttribute('aria-pressed'), 'true');
savedButton().click();
assert.equal(document.activeElement, query('#saved-only'));
assert.match(query('#issuer-rows').textContent, /No issuers/);
localStorage.setItem('stratiq.watchlist.v1', '["1652044","unknown",null]');
window.dispatchEvent(new window.StorageEvent('storage', {key: 'stratiq.watchlist.v1'}));
assert.equal(savedButton().getAttribute('aria-pressed'), 'true');
assert.equal(query('#saved-count').textContent, '1 saved');
localStorage.setItem('stratiq.watchlist.v1', '{');
window.dispatchEvent(new window.StorageEvent('storage', {key: 'stratiq.watchlist.v1'}));
assert.equal(query('#saved-count').textContent, '0 saved');
query('#saved-only').click();
Object.defineProperty(globalThis, 'localStorage', {value: {
  setItem() { throw new Error('storage unavailable'); },
}});
savedButton().click();
assert.equal(savedButton().getAttribute('aria-pressed'), 'true');
assert.match(query('#watchlist-status').textContent, /this session/);
const reopened = new JSDOM(await readFile(root + '/index.html', 'utf8'), {url: 'https://example.test/'});
globalThis.document = reopened.window.document;
globalThis.window = reopened.window;
reopened.window.localStorage.setItem('stratiq.watchlist.v1', '["1652044"]');
Object.defineProperty(globalThis, 'localStorage', {value: reopened.window.localStorage});
await import(new URL('?reopen', pathToFileURL(root + '/main.mjs')));
await new Promise(setImmediate);
assert.equal(savedButton().getAttribute('aria-pressed'), 'true');
console.log('DOM checks passed for cohort controls, exports, and watchlist storage and focus.');
